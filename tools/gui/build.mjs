import fs from 'node:fs';
import { createRequire } from 'node:module';
import { reviewMutation, reviewDraft, submitReview } from './domain.js';
const requireBuild = createRequire(new URL('./build-tools/package.json', import.meta.url));
const { build } = requireBuild('esbuild');
const body = fs.readFileSync(new URL('./client.source.js', import.meta.url), 'utf8');
const helpers = [reviewMutation, reviewDraft, submitReview].map(fn => fn.toString()).join('\n\n');
const entry = `import { clientContribution } from './rpc.js';\nexport function factory(require) {\n${helpers}\n${body}\n}`;
const result = await build({ stdin: { contents: entry, resolveDir: new URL('.', import.meta.url).pathname, sourcefile: 'client-entry.js', loader: 'js' }, bundle: true, format: 'cjs', platform: 'browser', write: false, minify: true, legalComments: 'eof' });
const artifact = `// Generated by tools/gui/build.mjs. Do not edit this artifact.\nwindow.__ModuleLoader__.load({id:'@local/dsh-independent-auto-review-settings',factory(require){const module={exports:{}};const exports=module.exports;\n${result.outputFiles[0].text}\nreturn module.exports.factory(require);}});\n`;
fs.writeFileSync(new URL('./client.js', import.meta.url), artifact);
console.log('Built the self-contained Client artifact.');
